from sqlalchemy import Column, String, DateTime, Float, JSON, ForeignKey, Boolean
from sqlalchemy.ext.mutable import MutableList
from sqlalchemy.sql import func
from db import Base
import uuid

def generate_order_id():
    return f"ORD-{uuid.uuid4().hex[:8].upper()}"

class Order(Base):
    __tablename__ = "orders"

    order_id = Column(String, primary_key=True, index=True, default=generate_order_id)
    customer_id = Column(String, ForeignKey("customer_users.customer_id"), nullable=False, index=True)
    
    # Nullable initially. Populated AFTER the customer selects a winning bid.
    shop_id = Column(String, ForeignKey("pharma_shop_users.shop_id"), nullable=True, index=True)

    order_type = Column(String, nullable=False, default="cart") # "cart" or "prescription"
    prescription_url = Column(String, nullable=True) 
    
    # Delivery Info (Dropoff details for Caby)
    receiver_name = Column(String, nullable=False)
    receiver_phone = Column(String, nullable=False)
    delivery_address = Column(String, nullable=False) # Flattened from JSON for easier Caby sync
    delivery_lat = Column(Float, nullable=False)      # Required for Caby routing
    delivery_lng = Column(Float, nullable=False)      # Required for Caby routing

    # Specifics mapped to Caby's dedicated Medicine Delivery service
    is_emergency = Column(Boolean, default=False, nullable=False)
    delivery_instructions = Column(String, nullable=True)

    # Logistics Integration
    caby_order_id = Column(String, nullable=True, index=True) # The ID generated by the Caby Database
    distance_km = Column(Float, nullable=True) # Calculated distance between Shop and Customer

    # Initial requested items (from Cart). Once a bid is accepted, these get replaced by the agreed `proposed_items`
    items = Column(MutableList.as_mutable(JSON), nullable=False, default=list)

    # Financials
    item_total = Column(Float, nullable=False, default=0.0)
    platform_fee = Column(Float, nullable=False, default=0.0)
    delivery_fee = Column(Float, nullable=False, default=0.0) # Will be populated via Caby's calculate-fare endpoint
    taxes = Column(Float, nullable=False, default=0.0)
    total_bill_amount = Column(Float, nullable=False, default=0.0)

    # Payment
    payment_mode = Column(String, nullable=False) # "cod" or "online"
    payment_status = Column(String, nullable=False, default="pending") 
    transaction_id = Column(String, nullable=True) # Razorpay ID

    # THE UPGRADED LIFECYCLE:
    # bidding (timer active) -> checkout_pending (bid selected) -> 
    # accepted (paid/cod confirmed) -> packing -> finding_driver (Caby sync) -> 
    # out_for_delivery -> delivered
    order_status = Column(String, nullable=False, default="bidding", index=True)

    # Rider details (Synced from Caby WebSockets)
    rider_id = Column(String, nullable=True)
    rider_name = Column(String, nullable=True)
    rider_phone = Column(String, nullable=True)
    rider_lat = Column(Float, nullable=True) # Live tracking synced from Caby
    rider_lng = Column(Float, nullable=True) # Live tracking synced from Caby
    vehicle_number = Column(String, nullable=True)
    vehicle_model = Column(String, nullable=True)
    
    # Verification OTPs synced from Caby
    pickup_otp = Column(String, nullable=True)
    drop_otp = Column(String, nullable=True)

    # Timestamps
    created_at = Column(DateTime(timezone=True), server_default=func.now())
    updated_at = Column(DateTime(timezone=True), onupdate=func.now(), server_default=func.now())
    accepted_at = Column(DateTime(timezone=True), nullable=True)
    delivered_at = Column(DateTime(timezone=True), nullable=True)

    from sqlalchemy.orm import relationship
    shop = relationship("PharmaShopUser", backref="orders", foreign_keys=[shop_id])

    def to_dict(self):
        return {
            "order_id": self.order_id,
            "customer_id": self.customer_id,
            "shop_id": self.shop_id,
            "shop_name": self.shop.shop_name if self.shop else None,
            "shop_phone": self.shop.phone if self.shop else None,
            "shop_lat": self.shop.latitude if self.shop else None,
            "shop_lng": self.shop.longitude if self.shop else None,
            "order_type": self.order_type,
            "order_status": self.order_status,
            "delivery_address": self.delivery_address,
            "delivery_lat": self.delivery_lat,
            "delivery_lng": self.delivery_lng,
            "caby_order_id": self.caby_order_id,
            "is_emergency": self.is_emergency,
            "delivery_instructions": self.delivery_instructions,
            "distance_km": self.distance_km,
            "items": self.items,
            "total_bill_amount": self.total_bill_amount,
            "delivery_fee": self.delivery_fee,
            "payment_mode": self.payment_mode,
            "payment_status": self.payment_status,
            "rider_name": self.rider_name,
            "rider_phone": self.rider_phone,
            "pickup_otp": self.pickup_otp,
            "drop_otp": self.drop_otp,
            "created_at": self.created_at.isoformat() if self.created_at else None
        }
