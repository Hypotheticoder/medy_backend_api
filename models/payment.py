from sqlalchemy import Column, String, Float, DateTime
from sqlalchemy.sql import func
from db import Base
import uuid

class PaymentTransaction(Base):
    __tablename__ = "payment_transactions"

    transaction_id = Column(String, primary_key=True, default=lambda: uuid.uuid4().hex)
    order_id = Column(String, nullable=False, index=True) # Can be LabBooking or MedicineOrder
    
    # 🚨 Razorpay Specific Columns
    razorpay_order_id = Column(String, nullable=True, index=True, unique=True) # Generated by Razorpay
    razorpay_payment_id = Column(String, nullable=True) # Populated after customer pays
    razorpay_signature = Column(String, nullable=True)  # Populated after customer pays
    
    amount = Column(Float, nullable=False)
    status = Column(String, default="created", nullable=False) # created, paid, failed
    
    created_at = Column(DateTime(timezone=True), server_default=func.now())
